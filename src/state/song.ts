/**
 * Drop-in demos: any `*.json` SongFile in `./demos` is auto-registered, ordered
 * by filename, and listed *before* the hand-authored built-in below so
 * dropped-in songs lead the demo button row.
 *
 * **Fetched on click, not bundled** (song-mode.md REQ-11). Eagerly importing
 * them put the whole library — hundreds of kB of JSON — into the boot payload,
 * parsed as JS object literals and held resident, so the user could load one.
 * A `?url` glob keeps only the URLs (a handful of strings); the same treatment
 * `ZIP_DEMOS` below has always had.
 *
 * The trade the `?url` form makes is that the song's own `name` field is no
 * longer readable at build time — which is where `demos-index.json` comes in.
 * It is generated by `scripts/clean-demos.ts` (the pass that already parses
 * every demo) and guarded by `npm run check:demos`, so the button labels stay
 * byte-identical to the names inside the files. Filenames alone would not do:
 * `hacienda_neworder.json` is "Haçienda".
 */
const DEMO_URLS = import.meta.glob<string>('./demos/*.json', {
  eager: true,
  query: '?url',
  import: 'default',
});

export interface DemoRef {
  /** The song's own `name` — what the demo button says. */
  name: string;
  url: string;
  /** Generated facts + any hand-written blurb; absent for an unindexed demo. */
  meta?: DemoMeta;
}

export const JSON_DEMOS: DemoRef[] = Object.keys(DEMO_URLS)
  .sort()
  .map((path) => {
    const file = path.replace(/^.*\//, '');
    const meta = DEMO_INDEX[file];
    const ref: DemoRef = {
      name: meta?.name ?? file.replace(/\.(websynth\.)?json$/i, ''),
      url: DEMO_URLS[path]!,
    };
    if (meta) ref.meta = meta;
    return ref;
  });

