/**
 * How every user-facing song/demo name is ordered — the demo row (`demoNames`)
 * and the slot picker (`Song.list`), so the two cannot disagree about where a
 * name sits (song-mode.md REQ-12).
 *
 * `numeric` so the year-named demos read as numbers (1973 · 1979 · 1983 ·
 * 1985-1 · 1985-2) rather than lexically; `sensitivity: 'base'` so an accent
 * files under its base letter and case never splits the list in two.
 */
export const compareSongNames = (a: string, b: string): number =>
  a.localeCompare(b, undefined, { sensitivity: 'base', numeric: true });

export interface ChainData {
  enabled: boolean;
  steps: number[];
}

export interface SongFile {
  format: 'websynth-song';
  /** Hand-maintained alongside `SONG_VERSION` — TS cannot derive `1|…|N` from a
   *  number without recursive-type machinery this codebase doesn't use. */
  version: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  name: string;
  params: Record<string, number>;
  /** v1-v5: one track per bank. Since v6 this is still **track 1** only —
   *  tracks 2-4 live in the additive `seqTracks` (sequencer.md REQ-13). */
  seqBanks: SeqStep[][];
  /**
   * v6 — `seqTracks[bank][track]`, indexed by the REAL track number, so index 0
   * is always null (track 1 is `seqBanks`). An empty track is null. Costs one
   * null per bank and removes the off-by-one an "extra tracks" array invites.
   */
  seqTracks?: (SeqStep[] | null)[][];
  drumBanks: DrumCell[][][];
  seqChain: ChainData;
  drumChain: ChainData;
  // ---- v2: sampler (optional so v1 files still load) ----
  samplerBanks?: SamplerStep[][][];
  samplerChain?: ChainData;
  /** Filenames only — decoded audio is not embedded; user reloads files. */
  sampleNames?: (string | null)[];
  // ---- v3: XY Pad axis assignment (optional so v1/v2 files still load) ----
  xy?: XyAssign;
  // ---- v4: motion sequencer (optional so v1-v3 files still load) ----
  motionBanks?: MotionStep[][];
  /** Per-bank axis override; null = inherit the song's XY Pad assignment. */
  motionAssigns?: (MotionAssign | null)[];
  motionChain?: ChainData;
  /** v5 — the two extra single-param motion tracks per bank. */
  motionTracks?: (MotionTrack | null)[][];
  /**
   * v7 — one semitone offset per `seqChain` slot, parallel to `seqChain.steps`
   * (arrangement.md REQ-8). A **sibling** of `seqChain`, not a field inside it,
   * so `ChainData` keeps its exact shape and every v1-v6 file round-trips
   * byte-identically. Omitted when every offset is 0.
   */
  seqTranspose?: number[];
}

/**
 * The narrow sampler view `apply` needs to evict stale audio (song-mode.md
 * REQ-3b). Structural, so `state/` never imports the audio layer —
 * `SamplerMachine` satisfies it.
 */
export interface SamplerSlots {
  setBuffer(slot: number, buf: AudioBuffer | null): void;
}

/**
 * Split the store's 3-D seq banks into the v6 file shape: track 1 stays in
 * `seqBanks` (handled by the caller) and tracks 2-4 become `seqTracks`, with an
 * empty track written as null. When no extra track holds a step the key is
 * omitted entirely, so a one-track song serializes exactly as it did pre-v6.
 */
function splitSeqTracks(banks: SeqStep[][][]): { seqTracks?: (SeqStep[] | null)[][] } {
  const used = banks.some((bank) => bank.slice(1).some((row) => row.some((s) => s.on)));
  if (!used) return {};
  return {
    seqTracks: banks.map((bank) =>
      bank.map((row, t) => (t === 0 || !row.some((s) => s.on) ? null : row.map((s) => ({ ...s }))))),
  };
}

/** The inverse: rebuild `[bank][track][step]` for the store. Every version
 *  before 6 simply has no `seqTracks`, so its banks come back one-track. */
function mergeSeqTracks(file: SongFile): SeqStep[][][] {
  return file.seqBanks.map((track0, b) => {
    const bank = makeSeqBank();
    bank[0] = track0;
    const extra = file.seqTracks?.[b];
    if (extra) {
      for (let t = 1; t < bank.length; t++) {
        const row = extra[t];
        if (row) bank[t] = row;
      }
    }
    return bank;
  });
}

export const Song = {
  capture(bus: ParamBus, patterns: PatternStore, arr: Arrangement, name: string, xy?: XyPadStore): SongFile {
    const snap = patterns.snapshot();
    return {
      format: 'websynth-song',
      version: SONG_VERSION,
      name,
      params: bus.snapshot(),
      // Track 1 keeps the v1-v5 field; 2-4 ride in the additive one, omitted
      // entirely when empty so a one-track song is byte-identical to before.
      seqBanks: snap.seqBanks.map((bank) => bank[0]!.map((s) => ({ ...s }))),
      ...splitSeqTracks(snap.seqBanks),
      drumBanks: snap.drumBanks,
      seqChain: { enabled: arr.seq.enabled, steps: [...arr.seq.steps] },
      drumChain: { enabled: arr.drum.enabled, steps: [...arr.drum.steps] },
      samplerBanks: snap.samplerBanks,
      samplerChain: { enabled: arr.sampler.enabled, steps: [...arr.sampler.steps] },
      sampleNames: [...patterns.sampleNames],
      xy: xy ? xy.get() : { ...XY_DEFAULT_ASSIGN },
      motionBanks: snap.motionBanks,
      motionAssigns: snap.motionAssigns,
      motionTracks: snap.motionTracks,
      motionChain: { enabled: arr.motion.enabled, steps: [...arr.motion.steps] },
      // v7, and only when it says something: an all-zero array is what every
      // pre-v7 song has, so omitting it keeps those files byte-identical and
      // lets compactSongForExport's version floor stay below 7 (song-mode.md
      // REQ-16). Same trick seqTracks uses.
      ...(arr.seq.transpose.some((t) => t !== 0)
        ? { seqTranspose: [...arr.seq.transpose] }
        : {}),
    };
  },

  apply(
    file: SongFile,
    bus: ParamBus,
    patterns: PatternStore,
    arr: Arrangement,
    xyStore?: XyPadStore,
    sampler?: SamplerSlots,
  ): void {
    bus.resetDefaults();      // authoritative: clear stale params before applying
    bus.restore(file.params);
    // A slot's decoded buffer belongs to the NAME beside it, so evict the audio
    // of every slot this file renames (song-mode.md REQ-3b) — otherwise the
    // previous song's sample keeps playing under the new song's label, with no
    // .needs-reload hint to betray it. Done BEFORE restore so the store's own
    // sample-meta emit repaints each slot against the settled buffers. A file
    // that OMITS sampleNames renames nothing, so the REQ-3 inherit exception
    // below still holds for v1 files.
    if (sampler && file.sampleNames) {
      for (let i = 0; i < patterns.sampleNames.length; i++) {
        if ((file.sampleNames[i] ?? null) !== (patterns.sampleNames[i] ?? null)) {
          sampler.setBuffer(i, null);
        }
      }
    }
    // Motion is authoritative: a file that omits a motion section has it BLANKED,
    // never inherited from the previously-loaded song (song-mode.md REQ-3,
    // motion-sequencer.md "Old songs load unchanged"). Without the `?? blank`
    // fallbacks, restore's skip-on-undefined leaves the prior song's anchors /
    // tracks live and still automating. Sampler banks/names are deliberately left
    // to inherit (see the v1-apply test): a file with no sampler section keeps the
    // user's loaded kit rather than orphaning it.
    const blank = emptyPatternSnapshot();
    patterns.restore({
      seqBanks: mergeSeqTracks(file),
      drumBanks: file.drumBanks,
      samplerBanks: file.samplerBanks,
      sampleNames: file.sampleNames,
      motionBanks: file.motionBanks ?? blank.motionBanks,
      motionAssigns: file.motionAssigns ?? blank.motionAssigns,
      motionTracks: file.motionTracks ?? blank.motionTracks,
    });
    // `?? []` — not "leave it alone": apply() is authoritative (REQ-3), so a file
    // without transposes must clear the last song's, not inherit them. fitTranspose
    // pads to the chain length, so [] means every slot at 0.
    arr.setSeqChain(
      file.seqChain?.steps ?? [0],
      file.seqChain?.enabled ?? false,
      file.seqTranspose ?? [],
    );
    arr.setDrumChain(file.drumChain?.steps ?? [0], file.drumChain?.enabled ?? false);
    arr.setSamplerChain(file.samplerChain?.steps ?? [0], file.samplerChain?.enabled ?? false);
    arr.setMotionChain(file.motionChain?.steps ?? [0], file.motionChain?.enabled ?? false);
    xyStore?.set(file.xy ?? XY_DEFAULT_ASSIGN);
  },

  /**
   * Serialize to the *canonical compact* form: numbers rounded to 4 significant
   * figures and step cells written default-sparse (`compactSongForExport`).
   * `saveSlot`/project zips/share links are whitespace-compact; `download` passes
   * `pretty` (matching `npm run clean:demos` byte-for-byte) so an exported file
   * dropped into `src/state/demos/` keeps readable git diffs.
   * `apply()`/`restore` re-expand the defaults on load — sound is unchanged.
   */
  toJSON(file: SongFile, pretty = false): string {
    return JSON.stringify(compactSongForExport(file), null, pretty ? 2 : undefined);
  },

  fromJSON(text: string): SongFile | null {
    const res = Song.parse(text);
    return res.ok ? res.file : null;
  },

  /** Like `fromJSON` but returns field-level errors instead of collapsing to null. */
  parse(text: string): import('./song-validate').SongValidation {
    let parsed: unknown;
    try {
      parsed = JSON.parse(text);
    } catch (e) {
      return { ok: false, errors: ['File is not valid JSON: ' + (e as Error).message] };
    }
    // The compact authoring dialect expands to a canonical v3 file here, so
    // every ingest surface (Import, launchQueue, project zips, share links,
    // MCP) accepts it automatically. Input-only — see ADR-013.
    //
    // The expand/validate pass is inside a `try` too (untrusted-input.md REQ-2):
    // both walk payload-shaped structures, so a pathological one can still raise
    // a RangeError (stack) or similar. A refused song must look like a failed
    // validation to every caller, never an exception escaping the import path.
    try {
      if (isAuthorSong(parsed)) return expandAuthorSong(parsed);
      return validateSongFile(parsed);
    } catch (e) {
      return { ok: false, errors: ['This file could not be read: ' + (e as Error).message] };
    }
  },

  download(file: SongFile): void {
    const blob = new Blob([Song.toJSON(file, true) + '\n'], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${file.name.replace(/[^a-z0-9_-]+/gi, '_') || 'song'}.websynth.json`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  },

  readFile(f: File): Promise<SongFile | null> {
    return f.text().then((t) => Song.fromJSON(t));
  },

  /** Like `readFile` but returns field-level validation errors for the import UI. */
  parseFile(f: File): Promise<import('./song-validate').SongValidation> {
    return f.text().then((t) => Song.parse(t));
  },

  // ---- localStorage slots ----

  /**
   * Slot-picker contents: every JSON demo name (drop-in and built-in) plus the
   * user's stored slots, deduped and sorted. Drop-ins are listed even though
   * `loadSlot` cannot return them — they are fetched, not bundled (REQ-12) — so
   * the Song panel's Load button falls back to `loadDemo` for a name with no
   * stored slot. Zip demos stay out, as they always have: they are project
   * bundles, not song files.
   */
  list(): string[] {
    return [...new Set([
      ...JSON_DEMOS.map((d) => d.name),
      ...Object.keys(DEMO_SONGS),
      ...store.readIndex(),
    ])].sort(compareSongNames);
  },

  saveSlot(name: string, file: SongFile): void {
    store.writeRaw(name, Song.toJSON(file));
    store.addToIndex(name);
  },

  /**
   * Is there a **stored** slot under this name — i.e. would `saveSlot` destroy
   * something the user made? Deliberately not `list()`, which also reports demos
   * (nothing of the user's is lost by overwriting a demo name).
   */
  hasSlot(name: string): boolean {
    return store.readRaw(name) !== null;
  },

  /**
   * Is there a stored slot under this song's name holding something **else**?
   * The one test behind every "may I overwrite?" dialog (session-autosave.md
   * REQ-14b/14c) — no slot, or a slot already holding these exact bytes, is
   * false: there is nothing to lose, so there is nothing to ask.
   *
   * A name match alone is NOT the question. When the slot holds the exact bytes
   * the save would write, the write is a no-op, so re-opening the same share
   * link — or re-saving a song you have not touched — must not ask: a prompt
   * that returns however you answer it is one the user stops reading. Hence the
   * comparison against `saveSlot`'s own serialization: canonical and compact
   * (ADR-011), so equal songs give equal strings, and any encoding difference
   * errs toward asking.
   */
  slotDiffers(file: SongFile): boolean {
    const raw = store.readRaw(file.name);
    return raw !== null && raw !== Song.toJSON(file);
  },

  /**
   * Would writing this song to its slot destroy work the user would miss?
   * (session-autosave.md REQ-14/14b/14c.)
   *
   * A *plan*, not an action — the same idiom as `preset-file.ts` `planImport`:
   * the decision is pure and testable here, and the UI owns the dialog.
   *
   * `from` is the slot the current session came from, if any. Saving a song back
   * to the slot it came from is the normal edit loop and must stay one click;
   * every other write lands on music the user has not been working on, so it
   * asks. An import has no provenance at all — hence `planImportSave`.
   */
  planSlotSave(file: SongFile, from: string | null): { name: string; conflict: boolean } {
    return { name: file.name, conflict: file.name !== from && Song.slotDiffers(file) };
  },

  /**
   * `planSlotSave` for an import, which never has provenance: nothing about an
   * arriving file makes its name *yours* (session-autosave.md REQ-14,
   * untrusted-input.md REQ-9). The name comes from the file, so with a share
   * link it is attacker-chosen: a song called "My Song" would otherwise destroy
   * that slot at boot, and the load-undo toast cannot bring it back — it
   * restores the in-memory session, not localStorage.
   */
  planImportSave(file: SongFile): { name: string; conflict: boolean } {
    return Song.planSlotSave(file, null);
  },

  /**
   * A stored slot, else a **built-in** demo. Stays synchronous and JSON-only, so
   * the fetched demos (drop-in JSON and zip alike) are not reachable here —
   * `SongPanel.loadDemo` is the door that knows about all three (REQ-12).
   */
  loadSlot(name: string): SongFile | null {
    const raw = store.readRaw(name);
    if (raw) return Song.fromJSON(raw);
    return DEMO_SONGS[name] ?? null;
  },

  deleteSlot(name: string): void {
    store.remove(name);
  },
};

